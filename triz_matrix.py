def lookup(improving: int, worsening: int) -> list[int]:
    """矛盾マトリックスから推奨発明原理を取得する。"""
    if improving == worsening:
        return []
    return MATRIX.get((improving, worsening), [])


def get_param_name(param_id: int, lang: str = "ja") -> str:
    p = PARAMETERS.get(param_id, {})
    return p.get(lang, p.get("en", f"Parameter {param_id}"))


def describe_contradiction(improving: int, worsening: int) -> str:
    imp = get_param_name(improving)
    wor = get_param_name(worsening)
    principles = lookup(improving, worsening)
    if not principles:
        return f"パラメータ {improving}({imp}) ↑ vs {worsening}({wor}) — 推奨原理なし"
    return f"パラメータ {improving}({imp}) ↑ vs {worsening}({wor}) — 推奨原理: {principles}"
